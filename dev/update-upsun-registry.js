'use strict';

const fs = require('fs');
const path = require('path');
const {COMPOSE} = require('../lib/mapping/services');
const {registryType} = require('../lib/mapping/registry');

const normalizeUpstream = raw => String(raw || '').replace(/^\d+:/, '').match(/^\d+(\.\d+)*/)?.[0];
const multiArch = tag => ['amd64', 'arm64'].every(architecture =>
  tag?.images?.some(image => image.os === 'linux' && image.architecture === architecture));
const numericCompare = (a, b) => {
  const left = normalizeUpstream(a.replace(/^v/, '')).split('.').map(Number);
  const right = normalizeUpstream(b.replace(/^v/, '')).split('.').map(Number);
  for (let i = 0; i < Math.max(left.length, right.length); i++) {
    const delta = (right[i] || 0) - (left[i] || 0);
    if (delta) return delta;
  }
  return a.localeCompare(b);
};

const pinFormatter = (type, config) => {
  if (type === 'mercure') return version => `v${version}`;
  if (type === 'influxdb') return version => Number(version.split('.')[0]) >= 3 ? null : version;
  return config.tag || (version => version);
};

const chooseTag = async (request, docker) => {
  const {type, version, raw, config} = request;
  const upstream = normalizeUpstream(raw);
  if (!upstream) return {reason: 'missing package version'};
  if (upstream !== version && !upstream.startsWith(`${version}.`)) {
    return {reason: `upstream ${upstream} does not match version prefix`};
  }
  const format = pinFormatter(type, config);
  const candidate = format(upstream);
  if (!candidate) return {reason: 'InfluxDB 3 requires a different entrypoint'};
  if (multiArch(await docker.detail(config.image, candidate))) return {tag: candidate};
  const listed = await docker.list(config.image, `${version}.`);
  const candidates = listed.filter(tag => {
    const numeric = normalizeUpstream(tag.name.replace(/^v/, ''));
    return numeric?.startsWith(`${version}.`) && format(numeric) === tag.name;
  }).sort((a, b) => numericCompare(a.name, b.name));
  for (const tag of candidates) {
    if (multiArch(tag.images ? tag : await docker.detail(config.image, tag.name))) return {tag: tag.name};
  }
  return {reason: 'no matching linux/amd64 and linux/arm64 Docker Hub tag'};
};

const buildTables = async (registry, docker, report = message => console.error(message)) => {
  const images = {};
  const tags = {};
  for (const type of Object.keys(registry).sort()) {
    const image = registry[type];
    images[type] = {docs: image.docs.url, versions: {}};
    for (const version of Object.keys(image.versions).sort()) {
      const entry = image.versions[version];
      const eol = entry.upstream?.eolFrom?.slice(0, 10);
      images[type].versions[version] = {status: entry.upsun.status, ...(eol ? {eol} : {})};
    }
  }
  for (const type of [...new Set(Object.keys(COMPOSE).map(registryType))].sort()) {
    if (!registry[type]) continue;
    for (const version of Object.keys(registry[type].versions).sort()) {
      const entry = registry[type].versions[version];
      if (['retired', 'decommissioned'].includes(entry.upsun.status)) continue;
      const result = await chooseTag({type, version, raw: entry.manifest?.package_version?.raw,
        config: COMPOSE[type]}, docker);
      if (result.tag) {
        tags[type] ||= {};
        tags[type][version] = result.tag;
      } else report(`unpinned ${type}:${version} (${result.reason})`);
    }
  }
  return {IMAGES: images, TAGS: tags};
};

const literal = (value, indent = 0) => {
  if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, '\\\'')}'`;
  const entries = Object.keys(value).sort().map(key =>
    `${' '.repeat(indent + 2)}${literal(key)}: ${literal(value[key], indent + 2)},`);
  return `Object.freeze({\n${entries.join('\n')}\n${' '.repeat(indent)}})`;
};

const render = (tables, source) => `'use strict';

// Generated by dev/update-upsun-registry.js. Do not edit by hand; rerun the script instead.

const IMAGES = ${literal(tables.IMAGES)};

const TAGS = ${literal(tables.TAGS)};

const SOURCE = ${literal(source)};

module.exports = Object.freeze({IMAGES, TAGS, SOURCE});
`;

const fetchJson = async url => {
  const response = await fetch(url, {signal: AbortSignal.timeout(30000)});
  if (response.status === 404) return null;
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.json();
};

const dockerClient = {
  detail: (image, tag) => fetchJson(`https://hub.docker.com/v2/repositories/` +
    `${image.includes('/') ? image : `library/${image}`}/tags/${encodeURIComponent(tag)}`),
  list: async (image, name) => {
    let url = `https://hub.docker.com/v2/repositories/${image.includes('/') ? image : `library/${image}`}` +
      `/tags?name=${encodeURIComponent(name)}&page_size=100`;
    const tags = [];
    while (url) {
      const page = await fetchJson(url);
      tags.push(...page.results);
      url = page.next;
    }
    return tags;
  },
};

const main = async () => {
  const ref = process.env.UPSUN_META_REF || 'master';
  const source = {repo: 'upsun/meta', ref};
  let registry;
  if (process.env.UPSUN_META_DIR) {
    registry = JSON.parse(fs.readFileSync(path.join(process.env.UPSUN_META_DIR,
      'resources/image/registry.json'), 'utf8'));
  } else {
    try {
      const commit = await fetchJson(`https://api.github.com/repos/upsun/meta/commits/${encodeURIComponent(ref)}`);
      if (commit?.sha) source.commit = commit.sha;
    } catch (error) {
      console.error(`Upsun commit unavailable: ${error.message}`);
    }
    registry = await fetchJson(`https://raw.githubusercontent.com/upsun/meta/${source.commit || ref}` +
      '/resources/image/registry.json');
    if (!registry) throw new Error(`Registry not found at ${ref}; set UPSUN_META_REF to an available ref.`);
  }
  const tables = await buildTables(registry, dockerClient);
  const output = process.env.UPSUN_REGISTRY_OUTPUT || path.resolve(__dirname, '../lib/mapping/upsun-registry.js');
  fs.mkdirSync(path.dirname(output), {recursive: true});
  fs.writeFileSync(output, render(tables, source));
};

module.exports = {normalizeUpstream, chooseTag, buildTables, render, main};
if (require.main === module) {
  main().catch(error => {
    console.error(error);
    process.exitCode = 1;
  });
}
